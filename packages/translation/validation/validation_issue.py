class IssueSeverity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"
    # Backward compatibility aliases
    ERROR = "HIGH"
    WARNING = "MEDIUM"


class GateStatus(str, Enum):
    PASS = "PASS"
    RETRY = "RETRY"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"
    FAIL = "FAIL"
    NOT_RUN = "NOT_RUN"


